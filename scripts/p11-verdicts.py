"""Phase 11 verdicts from the GPU job's per-query arrays (rules: pipelines/phase11/OPERATIONALIZATION.md).

    python p11-verdicts.py --metrics <p11.json> --audit <audit.json> --config <config> --out <dir>

Writes <dir>/REPORT.md and <dir>/metrics.json. A 95% interval is a paired bootstrap over test queries.
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

import yaml


def paired(a, b, n, seed=0):
    """Mean of a - b with a 95% bootstrap interval, resampling queries."""
    rng = random.Random(seed)
    d = [x - y for x, y in zip(a, b)]
    m = len(d)
    boots = sorted(sum(d[rng.randrange(m)] for _ in range(m)) / m for _ in range(n))
    return {"diff": round(sum(d) / m, 4), "lo": round(boots[int(0.025 * n)], 4), "hi": round(boots[int(0.975 * n) - 1], 4)}


def verdict(r):
    return "supported" if r["lo"] > 0 else "falsified"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--metrics", required=True)
    ap.add_argument("--audit", required=True)
    ap.add_argument("--config", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    cfg = yaml.safe_load(open(a.config))
    M = json.loads(Path(a.metrics).read_text())
    au = json.loads(Path(a.audit).read_text())
    n = cfg["verdicts"]["bootstrap"]
    nm, mo = M["named"], M["models"]
    t = lambda x: mo[nm[x]]["test"]["hits"]
    rr = lambda x: mo[nm[x]]["test"]["rr"]
    H = {
        "H1": {"compare": f"{nm['k_all']} vs untrained", **paired(t("k_all"), t("untrained"), n)},
        "H2": {"compare": f"{nm['k_all']} vs raw abstract", **paired(t("k_all"), t("abstract"), n)},
        "H3": {"compare": f"{nm['k_all']} vs {nm['k_mid']}", **paired(t("k_all"), t("k_mid"), n)},
    }
    for h in H.values():
        h["verdict"] = verdict(h)
    for h, (x, y) in {"H1": ("k_all", "untrained"), "H2": ("k_all", "abstract"), "H3": ("k_all", "k_mid")}.items():
        H[h]["mrr"] = paired(rr(x), rr(y), n)
    # Reported, not tested: test top-10 by overlap quartile (low overlap = the source is hard to find by its words).
    ov = M["overlap"]["test"]
    known = sorted(v for v in ov if v is not None)
    cuts = [known[int(len(known) * q)] for q in (0.25, 0.5, 0.75)] if known else []
    quart = lambda v: None if v is None else sum(v > c for c in cuts)
    byq = {}
    for x in ("abstract", "untrained", "k_small", "k_mid", "k_all"):
        h = t(x)
        byq[x] = [round(sum(h[i] for i, v in enumerate(ov) if quart(v) == q) / max(1, sum(quart(v) == q for v in ov)), 4) for q in range(4)]
    res = {"hypotheses": H, "chosen_epochs": M["chosen_epochs"], "sizes": nm["sizes"], "audit": au["violations"],
           "models": {x: {s: {k: mo[x][s][k] for k in ("top10", "mrr")} for s in ("val", "test")} for x in mo},
           "test_queries": len(M["queries"]["test"]), "val_queries": len(M["queries"]["val"]),
           "by_overlap_quartile": {"cuts": [round(c, 4) for c in cuts], "top10": byq}}
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "metrics.json").write_text(json.dumps(res, indent=1))
    L = ["# Phase 11 report: training a model on analogy pairs", "",
         "Generated by `scripts/p11-verdicts.py` from the GPU job's per-query results; rules fixed in "
         "`pipelines/phase11/OPERATIONALIZATION.md` before any result. Training pairs are an estimated 82% borrowings "
         f"and 12% same product (hand check, n = 50); test pairs about 80/20. N = {nm['sizes'][2]} training pairs, under "
         "the 8,000 first planned. One seed per size.", "",
         f"Test queries: {res['test_queries']}; val queries: {res['val_queries']}; 1,000 candidates each; chance top-10 = 1%. "
         f"Epochs chosen on val at {nm['sizes'][1]} pairs: {M['chosen_epochs']}.", "",
         "## Verdicts (test top-10, paired bootstrap 95% interval)", "", "| | Comparison | Difference | Interval | Verdict |", "|---|---|---|---|---|"]
    for h, r in H.items():
        L.append(f"| **{h}** | {r['compare']} | {r['diff']:+.4f} | [{r['lo']:+.4f}, {r['hi']:+.4f}] | {r['verdict']} |")
    L += ["", "## Every model", "", "| Model | Val top-10 | Val MRR | Test top-10 | Test MRR |", "|---|---|---|---|---|"]
    for x, m in res["models"].items():
        L.append(f"| {x} | {m['val']['top10']:.3f} | {m['val']['mrr']:.3f} | {m['test']['top10']:.3f} | {m['test']['mrr']:.3f} |")
    L += ["", "## Test top-10 by word-overlap quartile (reported, not tested)", "",
          f"Quartile cuts: {res['by_overlap_quartile']['cuts']} (Q1 = lowest overlap: the source shares fewest words).", "",
          "| Model | Q1 | Q2 | Q3 | Q4 |", "|---|---|---|---|---|"]
    for x, v in byq.items():
        L.append(f"| {nm[x]} | " + " | ".join(f"{q:.3f}" for q in v) + " |")
    L += ["", "## Sample descriptions (first 5 test-order queries)", ""]
    for x, rows in M["samples"].items():
        L.append(f"**{x}**")
        L += [f"- {r['query']}: {r['text'][:300]}" for r in rows]
        L.append("")
    (out / "REPORT.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(json.dumps({h: (r["diff"], r["lo"], r["verdict"]) for h, r in H.items()}), flush=True)


if __name__ == "__main__":
    main()
