"""Phase 12 verdicts from the GPU job's per-query arrays (rules: pipelines/phase12/OPERATIONALIZATION.md).

    python p12-verdicts.py --metrics <p12.json> --audit <audit.json> --handcheck <handcheck.json> --config <config> --out <dir>

Writes <dir>/REPORT.md and <dir>/metrics.json. A 95% interval is a paired bootstrap over test queries.
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

import yaml

SPLITS = ("dev", "test", "test_near")


def paired(a, b, n, seed=0):
    """Mean of a - b with a 95% bootstrap interval, resampling queries."""
    rng = random.Random(seed)
    d = [x - y for x, y in zip(a, b)]
    m = len(d)
    boots = sorted(sum(d[rng.randrange(m)] for _ in range(m)) / m for _ in range(n))
    return {"diff": round(sum(d) / m, 4), "lo": round(boots[int(0.025 * n)], 4), "hi": round(boots[int(0.975 * n) - 1], 4)}


def main():
    ap = argparse.ArgumentParser()
    for x in ("metrics", "audit", "handcheck", "config", "out"):
        ap.add_argument(f"--{x}", required=True)
    a = ap.parse_args()
    cfg = yaml.safe_load(open(a.config))
    M = json.loads(Path(a.metrics).read_text())
    au = json.loads(Path(a.audit).read_text())
    hc = json.loads(Path(a.handcheck).read_text())
    n, floor = cfg["verdicts"]["bootstrap"], cfg["verdicts"]["h3_floor"]
    nm, mo = M["named"], M["models"]
    hits = lambda x, s: mo[nm[x]][s]["hits"]
    rr = lambda x, s: mo[nm[x]][s]["rr"]
    H = {
        "H1": {"question": "far-trained beats off the shelf, far test", "compare": f"{nm['far']} vs base",
               **paired(hits("far", "test"), hits("base", "test"), n)},
        "H2": {"question": "far-trained beats near-trained, far test", "compare": f"{nm['far']} vs {nm['near']}",
               **paired(hits("far", "test"), hits("near", "test"), n)},
        "H3": {"question": "far training costs at most 3 points on near test pairs", "compare": f"{nm['far']} vs base",
               **paired(hits("far", "test_near"), hits("base", "test_near"), n)},
    }
    H["H1"]["verdict"] = "supported" if H["H1"]["lo"] > 0 else "falsified"
    H["H2"]["verdict"] = "supported" if H["H2"]["lo"] > 0 else "falsified"
    H["H3"]["verdict"] = "supported" if H["H3"]["lo"] > floor else "falsified"
    for h, (x, y, s) in {"H1": ("far", "base", "test"), "H2": ("far", "near", "test"), "H3": ("far", "base", "test_near")}.items():
        H[h]["mrr"] = paired(rr(x, s), rr(y, s), n)

    # Reported, not tested: far test top-10 by quartile of the far measures (word overlap, second-encoder cosine).
    def by_quartile(measure):
        v = M[measure]["test"]
        s = sorted(v)
        cuts = [s[int(len(s) * q)] for q in (0.25, 0.5, 0.75)]
        qt = [sum(x > c for c in cuts) for x in v]
        return {"cuts": [round(c, 4) for c in cuts],
                "top10": {x: [round(sum(hits(x, "test")[i] for i in range(len(v)) if qt[i] == q) / max(1, qt.count(q)), 4)
                              for q in range(4)] for x in ("base", "far", "near")}}

    seeds = {x: mo[t]["test"]["top10"] for x, t in nm.items() if x == "far" or x.startswith("far_s")}
    res = {"hypotheses": H, "chosen_epochs": M["chosen_epochs"], "audit": au["violations"], "medians": au["medians"],
           "train": {"far": au["train_far"], "near": au["train_near"]}, "eval": au["eval"], "handcheck": hc,
           "models": {x: {s: {k: mo[x][s][k] for k in ("top10", "mrr")} for s in SPLITS} for x in mo},
           "seed_spread_far_test_top10": seeds,
           "by_quartile": {"overlap": by_quartile("overlap"), "cosine": by_quartile("cosine")}}
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "metrics.json").write_text(json.dumps(res, indent=1))
    ht = hc["test"]
    L = ["# Phase 12 report: can an encoder learn to match far analogies?", "",
         "Generated by `scripts/p12-verdicts.py` from the GPU job's per-query results; rules fixed in "
         "`pipelines/phase12/OPERATIONALIZATION.md` before any result.", "",
         f"Training pairs: {au['train_far']} far, {au['train_near']} near (the control). Queries: {au['eval']['test']} far "
         f"test, {au['eval']['test_near']} near test, {au['eval']['dev']} far dev; 1,000 candidates each; chance top-10 = 1%. "
         f"Epochs chosen on far dev: far {M['chosen_epochs']['far']}, near {M['chosen_epochs']['near']}.", "",
         f"Hand check of {ht['new']} far test pairs (Claude, RUBRIC.md, rater agreement {ht['rater_agreement']}): "
         f"{ht['kept']} real borrowings, {ht['same_product']} same product, {ht['unrelated']} unrelated.", "",
         "## Verdicts (top-10, paired bootstrap 95% interval)", "",
         "| | Question | Comparison | Difference | Interval | Verdict |", "|---|---|---|---|---|---|"]
    for h, r in H.items():
        L.append(f"| **{h}** | {r['question']} | {r['compare']} | {r['diff']:+.4f} | [{r['lo']:+.4f}, {r['hi']:+.4f}] | {r['verdict']} |")
    L += ["", "## Every model (top-10 / MRR)", "", "| Model | Far dev | Far test | Near test |", "|---|---|---|---|"]
    for x, m in res["models"].items():
        L.append(f"| {x} | " + " | ".join(f"{m[s]['top10']:.3f} / {m[s]['mrr']:.3f}" for s in SPLITS) + " |")
    L += ["", f"Seed spread, far test top-10: {seeds}", ""]
    for meas, title in (("overlap", "word overlap"), ("cosine", "second-encoder similarity")):
        b = res["by_quartile"][meas]
        L += [f"## Far test top-10 by {title} quartile (reported, not tested)", "",
              f"Cuts: {b['cuts']} (Q1 = farthest).", "", "| Model | Q1 | Q2 | Q3 | Q4 |", "|---|---|---|---|---|"]
        L += [f"| {nm[x]} | " + " | ".join(f"{q:.3f}" for q in v) + " |" for x, v in b["top10"].items()]
        L.append("")
    (out / "REPORT.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(json.dumps({h: (r["diff"], r["lo"], r["verdict"]) for h, r in H.items()}), flush=True)


if __name__ == "__main__":
    main()
